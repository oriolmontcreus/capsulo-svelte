/**
 * English admin UI messages: the source of truth. `es.ts` and `fr.ts` are typed against these
 * keys, so a missing translation fails the type check.
 *
 * `{name}` is replaced by the `name` param. A message with `one`/`other` forms (plus `zero`,
 * and whatever else the language's plural rules use) picks one by the `count` param.
 */
